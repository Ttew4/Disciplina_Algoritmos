semn = int(input("Conversor de número pra semana:\n "))

if (semn == 2):
    print("Segunda-feira")
elif (semn == 3):
    print("Terça-feira")
elif (semn == 4):
    print("Quarta-feira")
elif (semn == 5):
    print("Quinta-feira")
elif (semn == 6):
    print("Sexta-feira")
elif (semn == 7):
    print("Sábado")
elif (semn == 1):
    print("Domingo")
else:
    print("Valor inválido")